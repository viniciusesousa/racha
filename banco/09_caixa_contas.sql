-- =====================================================================
-- App do Racha — 09: caixa com DUAS CONTAS (Banco e Crédito na quadra)
-- =====================================================================
-- Só estrutura (sem dados reais). O histórico de jul–out/2026 é lançado
-- por um script separado, fora do git (banco/dados/09_dados_caixa_historico.sql).
--
-- Regras do caixa:
--   * Pix entra no BANCO (conta exclusiva do racha).
--   * Dinheiro e cartão entram no CRÉDITO NA QUADRA (pagos direto na
--     quadra, que abate do aluguel).
--   * Quadra (DW Esportes): valor por racha realizado, debitado do Crédito
--     na quadra. Ao abrir um racha novo, abrir_racha já lança essa despesa
--     (valor configurável). Se o jogo for em outra quadra, o admin ajusta
--     ou exclui a despesa no Caixa.
--   * Goleiro de aluguel: despesa no Banco (valor configurável).
--   * Transferência Banco -> Quadra (adiantamento) não é despesa: sai de
--     uma conta e entra na outra.
--   * Saldo inicial, rendimentos e entradas avulsas ficam em movimentos_conta.
--
-- O que este script faz:
--   1. forma de pagamento: novo valor 'dinheiro_ou_cartao' (só histórico:
--      pagamentos antigos sem Pix, que não dizem se foi dinheiro ou cartão);
--   2. despesas: colunas "conta" (banco/quadra, padrão banco) e "racha_id";
--   3. tabela nova movimentos_conta (somente admin);
--   4. configuracoes: valor_quadra (R$ 185) e valor_goleiro_aluguel (R$ 37,49);
--   5. abrir_racha: passa a lançar a despesa da quadra do racha novo;
--   6. visões v_extrato_caixa e v_saldo_contas (somente admin).
--
-- Compatível com o app já publicado (nenhuma coluna removida, mesma
-- assinatura de abrir_racha). Executar UMA VEZ; primeiro no racha-teste.
-- Tudo dentro de uma transação: se algo der erro, nada muda.
-- =====================================================================

begin;

-- ---------------------------------------------------------------------
-- 1. Forma de pagamento
-- ---------------------------------------------------------------------
-- Conta de cada forma: pix -> banco; as demais -> crédito na quadra.
alter table public.pagamentos drop constraint if exists pagamentos_forma_check;
alter table public.pagamentos
  add constraint pagamentos_forma_check
  check (forma in ('pix', 'dinheiro', 'cartao', 'nao_informado', 'dinheiro_ou_cartao'));

comment on column public.pagamentos.forma is
  'pix (entra no Banco); dinheiro, cartao (entram no Crédito na quadra); '
  'dinheiro_ou_cartao e nao_informado: só dados antigos (contam como Crédito na quadra).';


-- ---------------------------------------------------------------------
-- 2. Despesas: de qual conta saiu e (opcional) de qual racha é
-- ---------------------------------------------------------------------
-- racha_id com "on delete restrict": o banco não deixa excluir um racha
-- que tenha despesas ligadas (mesma regra das cobranças), para o caixa não
-- ficar com despesa solta. Se um dia a área do admin tiver a opção de
-- excluir racha, ela deve avisar e oferecer remover antes a despesa da quadra.
alter table public.despesas
  add column conta text not null default 'banco' check (conta in ('banco', 'quadra')),
  add column racha_id integer references public.rachas(id) on delete restrict;

create index despesas_racha_idx on public.despesas (racha_id);

comment on column public.despesas.conta is
  'De onde o dinheiro saiu: banco (conta do racha) ou quadra (crédito na quadra).';
comment on column public.despesas.racha_id is
  'Racha a que a despesa se refere (quadra, goleiro de aluguel). Opcional.';


-- ---------------------------------------------------------------------
-- 3. Movimentos que não são pagamento de jogador nem despesa
-- ---------------------------------------------------------------------
--   saldo_inicial  : saldo de partida de uma conta (um por conta; pode ser
--                    negativo — ex.: crédito na quadra já usado a mais);
--   rendimento     : rendimento da conta bancária;
--   entrada_avulsa : dinheiro que entrou sem ser pagamento de racha
--                    (ex.: reembolso absorvido pelo caixa);
--   transferencia  : sai de conta_origem e entra em conta_destino
--                    (ex.: adiantamento Banco -> Quadra). Não é despesa.
create table public.movimentos_conta (
  id              integer generated by default as identity primary key,
  data            date not null default current_date,
  tipo            text not null check (tipo in ('saldo_inicial', 'rendimento', 'entrada_avulsa', 'transferencia')),
  conta_origem    text check (conta_origem in ('banco', 'quadra')),
  conta_destino   text not null check (conta_destino in ('banco', 'quadra')),
  valor           numeric(10,2) not null,
  descricao       text not null,
  registrado_por  uuid default auth.uid() references auth.users(id) on delete set null,
  criado_em       timestamptz not null default now(),
  -- Só a transferência tem conta de origem, e ela deve ser diferente do destino.
  constraint movimentos_conta_origem check ((tipo = 'transferencia') = (conta_origem is not null)),
  constraint movimentos_conta_diferentes check (conta_origem is distinct from conta_destino),
  -- Valor sempre positivo; só o saldo inicial pode ser negativo (mas não zero).
  constraint movimentos_conta_valor check (valor > 0 or (tipo = 'saldo_inicial' and valor <> 0))
);

-- Um único saldo inicial por conta (para corrigir, altera-se o existente).
create unique index movimentos_conta_saldo_inicial_unico
  on public.movimentos_conta (conta_destino) where tipo = 'saldo_inicial';

comment on table public.movimentos_conta is
  'Saldo inicial, rendimentos, entradas avulsas e transferências entre Banco e Crédito na quadra (somente administradores).';

alter table public.movimentos_conta enable row level security;
create policy "somente admin" on public.movimentos_conta
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

revoke all on table public.movimentos_conta from anon;
grant select, insert, update, delete on table public.movimentos_conta to authenticated;
grant usage, select on sequence public.movimentos_conta_id_seq to authenticated;


-- ---------------------------------------------------------------------
-- 4. Configurações: valores da quadra e do goleiro de aluguel
-- ---------------------------------------------------------------------
alter table public.configuracoes
  add column valor_quadra numeric(10,2) not null default 185 check (valor_quadra >= 0),
  add column valor_goleiro_aluguel numeric(10,2) not null default 37.49 check (valor_goleiro_aluguel >= 0);

comment on column public.configuracoes.valor_quadra is
  'Aluguel da quadra por racha, debitado do Crédito na quadra ao abrir o racha (0 = não lança).';
comment on column public.configuracoes.valor_goleiro_aluguel is
  'Valor do goleiro de aluguel (botão rápido do fechamento), pago pelo Banco.';


-- ---------------------------------------------------------------------
-- 5. abrir_racha: igual ao do 08, mais a despesa da quadra do racha NOVO
-- ---------------------------------------------------------------------
-- (create or replace mantém as permissões do 08: só usuários logados
--  executam, e a própria função recusa quem não é admin.)
create or replace function public.abrir_racha(p_data date, p_valor numeric default null)
returns table (racha_id integer, partida_id integer, ja_existia boolean)
language plpgsql
security invoker
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_racha   integer;
  v_partida integer;
  v_valor   numeric;
  v_quadra  numeric;
begin
  if not public.eh_admin() then
    raise exception 'Acesso negado: somente administradores.' using errcode = '42501';
  end if;

  select r.id into v_racha from public.rachas r where r.data_jogo = p_data;
  if v_racha is not null then
    select p.id into v_partida from public.partidas p where p.racha_id = v_racha and p.numero = 1;
    if v_partida is null then
      insert into public.partidas (racha_id, numero) values (v_racha, 1) returning id into v_partida;
    end if;
    return query select v_racha, v_partida, true;
    return;
  end if;

  v_valor := coalesce(p_valor, (select c.valor_padrao_racha from public.configuracoes c limit 1), 0);
  insert into public.rachas (data_jogo, valor_cobrado, situacao, origem, tem_times)
  values (p_data, v_valor, 'realizado', 'app', true)
  returning id into v_racha;
  insert into public.partidas (racha_id, numero) values (v_racha, 1) returning id into v_partida;

  -- Novo no 09: o aluguel da quadra sai do Crédito na quadra.
  v_quadra := coalesce((select c.valor_quadra from public.configuracoes c limit 1), 0);
  if v_quadra > 0 then
    insert into public.despesas (data, descricao, categoria, valor, conta, racha_id)
    values (p_data, 'Quadra — racha de ' || to_char(p_data, 'DD/MM/YYYY'), 'Quadra', v_quadra, 'quadra', v_racha);
  end if;

  return query select v_racha, v_partida, false;
end;
$$;


-- ---------------------------------------------------------------------
-- 6. Extrato e saldo por conta (somente admin)
-- ---------------------------------------------------------------------
-- Cada linha é uma entrada (+) ou saída (−) em UMA conta. A transferência
-- aparece duas vezes: − na origem e + no destino.
-- "security_invoker": obedece ao RLS de quem consulta (só admin vê).
create view public.v_extrato_caixa
with (security_invoker = true) as
select 'pagamento'::text as origem, p.id, p.data_pagamento as data,
       case when p.forma = 'pix' then 'banco' else 'quadra' end as conta,
       p.valor as valor, 'Pagamento — ' || j.nome as descricao, p.forma as detalhe
from public.pagamentos p
join public.jogadores j on j.id = p.jogador_id
union all
select 'despesa', d.id, d.data, d.conta, -d.valor, d.descricao, d.categoria
from public.despesas d
union all
select 'movimento', m.id, m.data, m.conta_destino, m.valor, m.descricao, m.tipo
from public.movimentos_conta m
union all
select 'movimento', m.id, m.data, m.conta_origem, -m.valor, m.descricao, m.tipo
from public.movimentos_conta m
where m.tipo = 'transferencia';

comment on view public.v_extrato_caixa is
  'Extrato do caixa: entradas (+) e saídas (−) por conta (banco / quadra). Só admin enxerga.';

create view public.v_saldo_contas
with (security_invoker = true) as
select c.conta, coalesce(sum(e.valor), 0)::numeric(12,2) as saldo
from (values ('banco'), ('quadra')) as c(conta)
left join public.v_extrato_caixa e on e.conta = c.conta
group by c.conta;

comment on view public.v_saldo_contas is
  'Saldo atual de cada conta: banco e quadra (crédito na quadra). Só admin enxerga.';

revoke all on public.v_extrato_caixa, public.v_saldo_contas from anon, authenticated;
grant select on public.v_extrato_caixa, public.v_saldo_contas to authenticated;

commit;

-- Resultado na tela: os dois saldos (no banco novo, os dois começam em 0).
select conta, saldo from public.v_saldo_contas order by conta;
