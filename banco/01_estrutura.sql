-- =====================================================================
-- App do Racha — estrutura do banco de dados (Supabase / PostgreSQL)
-- =====================================================================
-- Este script cria todas as tabelas, regras e permissões do app.
-- Ele deve ser executado UMA ÚNICA VEZ, em um projeto Supabase vazio,
-- pelo "SQL Editor" do painel do Supabase.
--
-- Tudo está dentro de uma transação (BEGIN ... COMMIT): se qualquer
-- parte der erro, nada é criado e o banco fica como estava.
--
-- Observação sobre o placar: ele NÃO é guardado em nenhuma tabela.
-- O placar de cada time é calculado na hora da consulta:
--   gols dos jogadores do time + gols contra feitos pelo time adversário.
-- O mesmo vale para os rankings: sempre calculados a partir dos
-- lançamentos (escalações, presenças e ajustes), nunca guardados prontos.
-- =====================================================================

begin;


-- =====================================================================
-- 1. JOGADORES
-- =====================================================================
-- Cadastro de todas as pessoas que já jogaram o racha.
-- O id é gerado automaticamente ("generated by default"), mas também
-- aceita que a gente informe o número na importação. Assim os jogadores
-- vindos da planilha mantêm o mesmo id que tinham no Mocha.
create table public.jogadores (
  id         integer generated by default as identity primary key,
  nome       text not null,
  apelido    text,
  posicao    text,
  -- Tipo do jogador: só aceita estes três valores.
  tipo       text not null default 'linha'
             check (tipo in ('linha', 'goleiro', 'convidado')),
  -- Jogador ativo aparece nas listas do dia a dia; inativo fica só no histórico.
  ativo      boolean not null default true,
  criado_em  timestamptz not null default now()
);

comment on table public.jogadores is
  'Cadastro de jogadores (linha, goleiro ou convidado).';


-- =====================================================================
-- 2. RACHAS
-- =====================================================================
-- Cada linha é um dia de racha (uma quinta-feira, normalmente).
-- A data do jogo é ÚNICA: o banco recusa dois rachas no mesmo dia.
create table public.rachas (
  id             integer generated by default as identity primary key,
  data_jogo      date not null unique,
  -- Valor cobrado de cada jogador naquele racha (nunca negativo).
  valor_cobrado  numeric(10,2) not null default 0
                 check (valor_cobrado >= 0),
  -- 'realizado' = teve jogo; 'sem_jogo' = racha cancelado/não aconteceu.
  situacao       text not null default 'realizado'
                 check (situacao in ('realizado', 'sem_jogo')),
  -- De onde veio o registro:
  --   'mocha'      = importado do app antigo;
  --   'recuperado' = reconstruído a partir de anotações (ago/set 2026);
  --   'app'        = lançado no app novo.
  origem         text not null default 'app'
                 check (origem in ('mocha', 'recuperado', 'app')),
  -- Indica se o racha tem times A/B montados.
  -- Fica falso nos rachas recuperados (sem times e sem placar).
  tem_times      boolean not null default true,
  observacao     text,
  criado_em      timestamptz not null default now()
);

comment on table public.rachas is
  'Um registro por dia de jogo. A data do jogo não pode se repetir.';


-- =====================================================================
-- 3. PARTIDAS
-- =====================================================================
-- Um racha pode ter várias partidas (partida 1, partida 2, ...).
-- A combinação racha + número é ÚNICA: não existe "partida 1" duas vezes
-- no mesmo racha.
create table public.partidas (
  id        integer generated by default as identity primary key,
  -- Se o racha for excluído, as partidas dele são excluídas junto.
  racha_id  integer not null references public.rachas(id) on delete cascade,
  numero    integer not null check (numero >= 1),
  unique (racha_id, numero)
);

comment on table public.partidas is
  'Partidas de cada racha, numeradas 1, 2, 3...';


-- =====================================================================
-- 4. ESCALAÇÕES
-- =====================================================================
-- Quem jogou em cada partida, em qual equipe (A ou B), e o que fez em campo.
-- Cada jogador aparece no máximo UMA vez por partida
-- (a "chave primária" é a dupla partida + jogador).
create table public.escalacoes (
  partida_id    integer not null references public.partidas(id) on delete cascade,
  -- "restrict": não deixa excluir um jogador que já tem jogos registrados,
  -- para não apagar o histórico sem querer.
  jogador_id    integer not null references public.jogadores(id) on delete restrict,
  -- Equipe 'A' ou 'B'. Pode ficar vazia nos rachas recuperados (sem times).
  equipe        char(1) check (equipe in ('A', 'B')),
  -- Estatísticas da partida: nunca negativas.
  gols          integer not null default 0 check (gols >= 0),
  assistencias  integer not null default 0 check (assistencias >= 0),
  gols_contra   integer not null default 0 check (gols_contra >= 0),
  primary key (partida_id, jogador_id)
);

comment on table public.escalacoes is
  'Participação de cada jogador em cada partida: equipe, gols, assistências e gols contra.';


-- =====================================================================
-- 5. PRESENÇAS
-- =====================================================================
-- Quem esteve presente em cada racha (o dia todo, não por partida).
-- Também marca quem atuou como goleiro naquele dia — esse não paga.
-- Cada jogador aparece no máximo UMA vez por racha.
create table public.presencas (
  racha_id            integer not null references public.rachas(id) on delete cascade,
  jogador_id          integer not null references public.jogadores(id) on delete restrict,
  atuou_como_goleiro  boolean not null default false,
  primary key (racha_id, jogador_id)
);

comment on table public.presencas is
  'Presença de cada jogador em cada racha e se atuou como goleiro.';


-- =====================================================================
-- 6. COBRANÇAS  (financeiro — só admin)
-- =====================================================================
-- Quanto cada jogador deve por cada racha.
-- No máximo UMA cobrança por jogador por racha.
-- A dívida de um jogador = soma das cobranças − soma dos pagamentos.
create table public.cobrancas (
  -- "restrict": o banco NÃO deixa excluir um racha que tenha cobranças.
  -- Isso protege o histórico financeiro: para excluir o racha, é preciso
  -- antes remover (conscientemente) as cobranças dele.
  racha_id    integer not null references public.rachas(id) on delete restrict,
  jogador_id  integer not null references public.jogadores(id) on delete restrict,
  valor       numeric(10,2) not null check (valor >= 0),
  primary key (racha_id, jogador_id)
);

comment on table public.cobrancas is
  'Valor devido por jogador em cada racha (somente administradores).';


-- =====================================================================
-- 7. PAGAMENTOS  (financeiro — só admin)
-- =====================================================================
-- Cada pagamento recebido de um jogador. Não fica preso a um racha
-- específico: abate da dívida acumulada (pode quitar tudo ou só uma parte).
-- Também é a "entrada" do caixa.
create table public.pagamentos (
  id              integer generated by default as identity primary key,
  jogador_id      integer not null references public.jogadores(id) on delete restrict,
  -- Pagamento precisa ter valor maior que zero.
  valor           numeric(10,2) not null check (valor > 0),
  forma           text not null check (forma in ('pix', 'dinheiro', 'cartao')),
  data_pagamento  date not null default current_date,
  observacao      text,
  -- Quem registrou: preenchido automaticamente com o admin logado.
  registrado_por  uuid default auth.uid() references auth.users(id) on delete set null,
  criado_em       timestamptz not null default now()
);

comment on table public.pagamentos is
  'Pagamentos recebidos dos jogadores; são as entradas do caixa (somente administradores).';


-- =====================================================================
-- 8. DESPESAS  (caixa — só admin)
-- =====================================================================
-- Saídas do caixa: aluguel da quadra, bola, coletes etc.
-- Saldo do caixa = soma dos pagamentos − soma das despesas.
create table public.despesas (
  id              integer generated by default as identity primary key,
  data            date not null default current_date,
  descricao       text not null,
  categoria       text,
  valor           numeric(10,2) not null check (valor > 0),
  registrado_por  uuid default auth.uid() references auth.users(id) on delete set null,
  criado_em       timestamptz not null default now()
);

comment on table public.despesas is
  'Saídas do caixa lançadas manualmente (somente administradores).';


-- =====================================================================
-- 9. AJUSTES
-- =====================================================================
-- Correções manuais nas estatísticas (ex.: os campos manual_goals,
-- manual_assists e manual_wins da planilha do Mocha).
-- Cada ajuste é um registro com motivo, data e autor: assim dá para
-- saber depois quem mudou o quê e por quê (auditoria).
-- Os rankings somam estes ajustes aos números vindos das partidas.
create table public.ajustes (
  id          integer generated by default as identity primary key,
  jogador_id  integer not null references public.jogadores(id) on delete restrict,
  tipo        text not null
              check (tipo in ('gols', 'assistencias', 'vitorias', 'presencas')),
  -- A quantidade pode ser positiva (acrescentar) ou negativa (corrigir um
  -- lançamento a mais). Só não pode ser zero, porque não ajustaria nada.
  quantidade  integer not null check (quantidade <> 0),
  -- Motivo é obrigatório: todo ajuste precisa de justificativa.
  motivo      text not null,
  data        date not null default current_date,
  -- Autor: o admin logado. Fica vazio nos ajustes importados da planilha.
  autor       uuid default auth.uid() references auth.users(id) on delete set null,
  criado_em   timestamptz not null default now()
);

comment on table public.ajustes is
  'Ajustes manuais auditáveis nas estatísticas dos jogadores.';


-- =====================================================================
-- 10. CONFIGURAÇÕES  (só admin)
-- =====================================================================
-- Tabela com UMA ÚNICA linha, que guarda as configurações gerais.
-- O truque: a coluna "id" só aceita o valor verdadeiro (true) e é chave
-- primária — então é impossível existir uma segunda linha.
create table public.configuracoes (
  id                  boolean primary key default true check (id),
  -- Valor padrão sugerido ao criar um novo racha (nunca negativo).
  valor_padrao_racha  numeric(10,2) not null default 0
                      check (valor_padrao_racha >= 0)
);

comment on table public.configuracoes is
  'Configurações gerais do app (uma única linha).';

-- Cria a linha de configuração com valor 0.
-- O valor real deve ser ajustado depois pelo administrador.
insert into public.configuracoes (id, valor_padrao_racha) values (true, 0);


-- =====================================================================
-- 11. ADMINISTRADORES
-- =====================================================================
-- Lista de quem é administrador. Cada linha aponta para um usuário de
-- login do Supabase (tabela auth.users, criada pelo próprio Supabase).
-- Para tornar alguém admin: criar o usuário em Authentication > Users e
-- depois inserir o id dele aqui.
create table public.administradores (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  criado_em  timestamptz not null default now()
);

comment on table public.administradores is
  'Usuários de login que têm permissão de administrador.';


-- =====================================================================
-- FUNÇÃO eh_admin()
-- =====================================================================
-- Responde "sim" (true) se o usuário logado está na tabela de
-- administradores, e "não" (false) em qualquer outro caso — inclusive
-- para quem acessa sem login.
--
-- "security definer": a função consulta a tabela administradores com
-- permissão própria, sem depender das regras de acesso dessa tabela.
-- Isso evita um "ciclo" (a regra da tabela administradores também usa
-- esta função).
-- "set search_path = ''": medida de segurança recomendada pelo Supabase
-- para funções desse tipo (obriga a usar nomes completos, ex.: public.x).
create or replace function public.eh_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.administradores
    where user_id = auth.uid()
  );
$$;

comment on function public.eh_admin() is
  'Retorna true se o usuário logado for administrador.';


-- =====================================================================
-- SEGURANÇA: ROW LEVEL SECURITY (RLS)
-- =====================================================================
-- Com o RLS ligado, o banco bloqueia TUDO por padrão. Só passa o que
-- for liberado explicitamente pelas regras ("policies") abaixo.
-- Isso garante que o financeiro fique protegido no próprio banco,
-- mesmo que alguém tente acessar sem passar pelas telas do app.
--
-- Papéis do Supabase:
--   anon          = quem acessa sem login (os jogadores);
--   authenticated = quem fez login (os administradores).

alter table public.jogadores       enable row level security;
alter table public.rachas          enable row level security;
alter table public.partidas        enable row level security;
alter table public.escalacoes      enable row level security;
alter table public.presencas       enable row level security;
alter table public.cobrancas       enable row level security;
alter table public.pagamentos      enable row level security;
alter table public.despesas        enable row level security;
alter table public.ajustes         enable row level security;
alter table public.configuracoes   enable row level security;
alter table public.administradores enable row level security;


-- ---------------------------------------------------------------------
-- Tabelas PÚBLICAS para leitura:
-- jogadores, rachas, partidas, escalacoes, presencas, ajustes.
-- Qualquer pessoa pode LER. Só admin pode inserir, alterar ou excluir.
-- ---------------------------------------------------------------------

-- Jogadores
create policy "leitura publica" on public.jogadores
  for select to anon, authenticated using (true);
create policy "escrita somente admin" on public.jogadores
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

-- Rachas
create policy "leitura publica" on public.rachas
  for select to anon, authenticated using (true);
create policy "escrita somente admin" on public.rachas
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

-- Partidas
create policy "leitura publica" on public.partidas
  for select to anon, authenticated using (true);
create policy "escrita somente admin" on public.partidas
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

-- Escalações
create policy "leitura publica" on public.escalacoes
  for select to anon, authenticated using (true);
create policy "escrita somente admin" on public.escalacoes
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

-- Presenças
create policy "leitura publica" on public.presencas
  for select to anon, authenticated using (true);
create policy "escrita somente admin" on public.presencas
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

-- Ajustes
create policy "leitura publica" on public.ajustes
  for select to anon, authenticated using (true);
create policy "escrita somente admin" on public.ajustes
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());


-- ---------------------------------------------------------------------
-- Tabelas RESTRITAS (leitura e escrita só para admin):
-- cobrancas, pagamentos, despesas, configuracoes, administradores.
-- Quem não é admin não consegue nem ver que existem linhas nelas.
-- ---------------------------------------------------------------------

create policy "somente admin" on public.cobrancas
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

create policy "somente admin" on public.pagamentos
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

create policy "somente admin" on public.despesas
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

create policy "somente admin" on public.configuracoes
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());

create policy "somente admin" on public.administradores
  for all to authenticated using (public.eh_admin()) with check (public.eh_admin());


-- =====================================================================
-- PERMISSÕES EXPLÍCITAS
-- =====================================================================
-- Segunda camada de proteção, além do RLS.
-- O RLS decide QUAIS LINHAS cada pessoa pode ver ou mudar. As permissões
-- abaixo decidem, antes disso, se a pessoa pode sequer TOCAR na tabela.
-- Assim, mesmo que uma regra de RLS fique errada no futuro, quem acessa
-- sem login continua sem conseguir escrever nada nem ver o financeiro.

-- 1) Tira TODAS as permissões de quem acessa sem login (anon)
--    nas 11 tabelas, para começar do zero.
revoke all on table
  public.jogadores, public.rachas, public.partidas, public.escalacoes,
  public.presencas, public.cobrancas, public.pagamentos, public.despesas,
  public.ajustes, public.configuracoes, public.administradores
from anon;

-- 2) Devolve ao anon somente a LEITURA das tabelas públicas.
--    As tabelas do financeiro ficam de fora: o anon não tem acesso nenhum.
grant select on table
  public.jogadores, public.rachas, public.partidas, public.escalacoes,
  public.presencas, public.ajustes
to anon;

-- 3) Quem fez login (authenticated) recebe permissão de ler e escrever nas
--    11 tabelas. Atenção: isso NÃO torna qualquer usuário logado um admin —
--    o RLS continua exigindo eh_admin() para escrever e para ver o financeiro.
grant select, insert, update, delete on table
  public.jogadores, public.rachas, public.partidas, public.escalacoes,
  public.presencas, public.cobrancas, public.pagamentos, public.despesas,
  public.ajustes, public.configuracoes, public.administradores
to authenticated;

-- 4) Os ids automáticos usam "sequências" (contadores). O usuário logado
--    precisa poder usá-las para gerar o próximo id ao inserir um registro.
grant usage, select on all sequences in schema public to authenticated;

-- 5) Todos precisam poder chamar a função eh_admin(), porque as regras de
--    RLS a usam. Para quem não é admin, ela simplesmente responde "não".
grant execute on function public.eh_admin() to anon, authenticated;


-- =====================================================================
-- ÍNDICES
-- =====================================================================
-- Índices funcionam como o índice de um livro: deixam as buscas mais
-- rápidas. As chaves únicas acima já criam índices automaticamente
-- (ex.: data_jogo, racha_id + numero, partida_id + jogador_id).
-- Aqui criamos os que faltam para as consultas de ranking e financeiro,
-- que buscam "tudo de um jogador".

-- Rankings de gols, assistências e vitórias: todas as partidas de um jogador.
create index escalacoes_jogador_idx on public.escalacoes (jogador_id);

-- Ranking de presença e sequências: todos os rachas de um jogador.
create index presencas_jogador_idx  on public.presencas (jogador_id);

-- Ajustes de um jogador, separados por tipo (gols, assistências...).
create index ajustes_jogador_tipo_idx on public.ajustes (jogador_id, tipo);

-- Tela "quem está devendo": cobranças e pagamentos de cada jogador.
create index cobrancas_jogador_idx  on public.cobrancas (jogador_id);
create index pagamentos_jogador_idx on public.pagamentos (jogador_id);

-- Extrato do caixa, ordenado por data.
create index pagamentos_data_idx on public.pagamentos (data_pagamento);
create index despesas_data_idx   on public.despesas (data);


commit;


-- =====================================================================
-- LEMBRETE PARA DEPOIS DA IMPORTAÇÃO DA PLANILHA
-- =====================================================================
-- Quando os jogadores (ou rachas) forem importados com o id informado
-- manualmente, o contador automático não "fica sabendo" disso. Depois da
-- importação, rodar os comandos abaixo para o próximo id gerado continuar
-- a partir do maior id existente (evita erro de id repetido):
--
-- select setval(pg_get_serial_sequence('public.jogadores', 'id'),
--               (select coalesce(max(id), 1) from public.jogadores));
-- select setval(pg_get_serial_sequence('public.rachas', 'id'),
--               (select coalesce(max(id), 1) from public.rachas));
-- select setval(pg_get_serial_sequence('public.partidas', 'id'),
--               (select coalesce(max(id), 1) from public.partidas));
